export type TranslationKey = keyof typeof copy;

export function translate(language: UILanguage, key: TranslationKey) {
  return copy[key][language];
}

export function useI18n() {
  const { settings } = useWorkout();
  const language = settings.uiLanguage;
  return {
    language,
    locale: language === 'sv' ? 'sv-SE' : 'en-US',
    t: (key: TranslationKey) => translate(language, key)
  };
}

